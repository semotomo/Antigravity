test('通知を書けずに終了したpending runを同じUUIDで一度だけ発見し、送信せず状態を確認する', async () => {
  const attempt = randomUUID()
  const begin = await role('service_role', null, () => db.query('SELECT public.begin_product_master_sync_request(7,$1,clock_timestamp()+interval \'1 minute\') AS result', [attempt]))
  assert.equal(begin.rows[0].result.accepted, true)
  const gate = () => role('service_role', null, () => db.query('SELECT public.get_product_master_sync_notification_gate(7) AS result'))
  assert.equal((await gate()).rows[0].result.blocked, true)
  assert.equal((await gate()).rows[0].result.blocked, true)
  const rows = (await db.query('SELECT source,outcome,code,run_id,resolved_at FROM public.product_master_sync_notifications WHERE attempt_id=$1', [attempt])).rows
  assert.deepEqual(rows, [{ source: 'recovery', outcome: 'unknown', code: 'PRODUCT_SYNC_UNKNOWN', run_id: attempt, resolved_at: null }])
  await db.query("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1", [attempt])
  assert.equal((await gate()).rows[0].result.blocked, false)
  assert.equal((await db.query('SELECT resolution_outcome FROM public.product_master_sync_notifications WHERE attempt_id=$1', [attempt])).rows[0].resolution_outcome, 'rejected')
})

