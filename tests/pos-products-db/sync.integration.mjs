after(async () => db.close())
async function role(name, fn) { await db.exec(`SET ROLE ${name}`); try { return await fn() } finally { await db.exec('RESET ROLE') } }
const rpc = (sql, args) => role('service_role', async () => (await db.query(sql, args)).rows[0].result)
const begin = (store=6) => rpc('SELECT public.begin_product_master_sync($1) AS result', [store])
const apply = (run, records, store=run.storeId) => rpc('SELECT public.apply_product_master_sync($1,$2,$3::jsonb) AS result', [run.id,store,JSON.stringify(records)])
const row = (jan,store=6) => ({store_id:store,jan_code:jan,product_name:'同期商品',category:'分類',product_group:'分類',selling_price:999,cost_price:499,markup_rate:0.5005,is_active:true,tags:store===6?'わんわん':'本店'})
const products = async store => (await db.query('SELECT * FROM public.products WHERE store_id=$1 ORDER BY id',[store])).rows

test('匿名・利用者は同期開始と一括反映、版番号の直接書換えを行えない', async () => {
  for (const who of ['anon','authenticated']) {
    await assert.rejects(role(who, () => db.query('SELECT public.begin_product_master_sync(6)')))
    await assert.rejects(role(who, () => db.query('SELECT public.apply_product_master_sync($1,6,$2)',[randomUUID(),'[]'])))
  }
  await assert.rejects(role('service_role', () => db.exec('UPDATE public.product_master_store_versions SET revision=0')))
  await assert.rejects(begin(8))
})
test('商品更新・未取得商品の無効化を店舗内で原子的に行い、ブランドと手動停止を保持する', async () => {
  await db.exec(`INSERT INTO public.products(store_id,jan_code,product_name,brand) VALUES(6,'001','旧名前','維持'),(6,'002','欠落','維持'),(7,'001','他店舗','他店');
    INSERT INTO public.inventory_product_settings(store_id,product_id,manually_inactive,updated_by)
      SELECT 6,id,true,'${manager}' FROM public.products WHERE store_id=6 AND jan_code='001';`)
  const other = await products(7)
  const run=await begin(); const result=await apply(run,[row('001'),row('003')])
  assert.equal(result.count,2);assert.equal(result.deactivatedCount,1)
  const current=await products(6)
  assert.equal(current.find(p=>p.jan_code==='001').brand,'維持')
  assert.equal(current.find(p=>p.jan_code==='001').is_active,false)
  assert.equal(current.find(p=>p.jan_code==='002').is_active,false)
  assert.equal(current.find(p=>p.jan_code==='003').cost_price,499)
  assert.deepEqual(await products(7),other)
})
test('応答消失後に同じ同期を再照合しても重複変更せず、別内容の再利用は拒否する', async () => {
  const run=await begin();const records=[row('001'),row('003')]
  const first=await apply(run,records);const before=await products(6)
  assert.deepEqual(await apply(run,records),first)
  assert.deepEqual(await products(6),before)
  await assert.rejects(apply(run,[row('004')]),/content conflict/)
})
test('CSV取得中の同店舗商品変更は同期全体を拒否し、入力値を戻さない', async () => {
  const run=await begin()
  await db.exec("UPDATE public.products SET selling_price=1234 WHERE store_id=6 AND jan_code='003'")
  const before=await products(6)
  await assert.rejects(apply(run,[row('003')]),/stale sync/)
  assert.deepEqual(await products(6),before)
})
test('同時取得した二つのCSVは先に完了した同期だけを適用する', async () => {
  const older=await begin();const winner=await begin()
  await apply(winner,[row('003')]);const before=await products(6)
  await assert.rejects(apply(older,[row('001')]),/stale sync/)
  assert.deepEqual(await products(6),before)
})
test('別店舗での編集は対象店舗の同期を妨げない', async () => {
  const run=await begin()
  await db.exec("UPDATE public.products SET product_name='別店舗の更新' WHERE store_id=7")
  assert.equal((await apply(run,[row('003')])).success,true)
})
test('空・他店舗・重複・不正金額・余計な列を含むCSVは部分更新も無効化も行わない', async () => {
  const invalid=[[],[row('003',7)],[row('003'),row('003')],[{...row('003'),cost_price:-1}],[{...row('003'),brand:'上書き禁止'}],[{...row('003'),is_active:false}]]
  for (const records of invalid) {
    const run=await begin(); const before=await products(6)
    await assert.rejects(apply(run,records))
    assert.deepEqual(await products(6),before)
  }
  const run=await begin();await assert.rejects(apply(run,[row('003')],7))
})
test('期限切れCSVは書き込まない', async () => {
  const run=await begin()
  await db.query("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1",[run.id])
  await assert.rejects(apply(run,[row('003')]),/expired/)
})
test('後続商品のDB制約違反は先行商品の更新もロールバックする', async () => {
  await db.exec("ALTER TABLE public.products ADD CONSTRAINT test_reject_name CHECK(product_name <> '制約違反')")
  const run=await begin();const before=await products(6)
  await assert.rejects(apply(run,[{...row('003'),product_name:'巻戻す更新'},{...row('005'),product_name:'制約違反'}]))
  assert.deepEqual(await products(6),before)
  await db.exec('ALTER TABLE public.products DROP CONSTRAINT test_reject_name')
})
test('実データ相当の4000商品を一括反映し、再取得した全商品数と値が一致する', async () => {
  const records=[row('003'),...Array.from({length:3999},(_,i)=>row('bulk'+String(i).padStart(5,'0')))]
  const run=await begin()
  const result=await apply(run,records)
  assert.equal(result.count,4000)
  const current=(await products(6)).filter(p=>p.is_active)
  assert.equal(current.length,4000)
  assert.ok(current.every(p=>p.cost_price===499&&p.selling_price===999))
  assert.deepEqual(new Set(current.map(p=>p.jan_code)),new Set(records.map(p=>p.jan_code)))
})

test('POS編集受付で古いCSVを無効にし、結果不明の操作中は新しい同期も開始させない', async () => {
  const run=await begin()
  const command={kind:'create',operationId:randomUUID(),storeId:6,janCode:'0490123456789',fields:{name:'新商品',groupId:'group6',price:'1000',cost:'500',supplierId:null}}
  await rpc('SELECT public.prepare_pos_product_operation($1,$2,NULL,$3) AS result',[manager,JSON.stringify(command),'a'.repeat(64)])
  const before=await products(6)
  await assert.rejects(apply(run,[row('003')]),/stale sync|pending product operation/)
  await assert.rejects(begin(),/pending product operation/)
  assert.deepEqual(await products(6),before)
  assert.equal((await begin(7)).storeId,7)
})
