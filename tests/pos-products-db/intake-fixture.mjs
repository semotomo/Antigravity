export const manager = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'
export const other = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'
export const staff = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc'
const migration = name => readFile(new URL('../../supabase/migrations/' + name, import.meta.url), 'utf8')

// PGliteと通常PostgreSQLの両方へ、同じ合成DDLと実migrationを適用する。
export async function setupIntakeDatabase(db) {
  await db.exec(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    GRANT USAGE ON SCHEMA auth TO authenticated,service_role;
    CREATE TABLE public.stores(id integer PRIMARY KEY); INSERT INTO public.stores VALUES(6),(7);
    INSERT INTO auth.users VALUES('${manager}'),('${other}'),('${staff}');
    CREATE TABLE public.products(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,store_id integer NOT NULL REFERENCES public.stores(id),
      jan_code text NOT NULL,product_name text,category text,product_group text,supplier_name text,
      cost_price integer,selling_price integer,markup_rate real,is_active boolean DEFAULT true,tags text,
      brand text,updated_at timestamptz DEFAULT clock_timestamp(),UNIQUE(store_id,jan_code),UNIQUE(id,store_id));`)
  await db.exec(await migration('20260823163000_inventory_phase1_schema.sql'))
  const alias = await migration('20260328173000_phase1_additive.sql')
  await db.exec(alias.slice(alias.indexOf('CREATE TABLE IF NOT EXISTS public.product_aliases'), alias.indexOf('CREATE UNIQUE INDEX IF NOT EXISTS idx_product_aliases_alias_source_unique')))
  await db.exec(`ALTER TABLE public.product_aliases ADD COLUMN store_id integer NOT NULL REFERENCES public.stores(id);
    CREATE UNIQUE INDEX alias_store_unique ON public.product_aliases(alias_name,source_system,store_id);
    INSERT INTO public.user_store_access(user_id,store_id,role) VALUES
      ('${manager}',6,'manager'),('${manager}',7,'manager'),('${other}',6,'manager'),('${staff}',6,'staff');`)
  const inventory = await migration('20260824090000_inventory_phase4_management.sql')
  await db.exec(inventory.slice(0, inventory.indexOf('CREATE OR REPLACE FUNCTION public.set_inventory_item_exclusion(')))
  for (const name of ['20260908120000_pos_product_operation_ledger.sql', '20260908121000_pos_product_operation_functions.sql',
    '20260910090000_product_master_sync_fence.sql', '20260910120000_pos_product_edit_apply.sql', '20261004120000_pos_product_edit_dispatch.sql',
    '20261005120000_pos_product_operation_cancellation.sql', '20261005121000_product_master_sync_notifications.sql',
    '20261005122000_product_master_write_cutover.sql', '20261005123000_product_master_sync_gateway.sql',
    '20261008120000_product_master_sync_excluded_code.sql', '20261010120000_pos_product_edit_not_sent.sql',
    '20261010210000_pos_product_edit_legacy_closure.sql', '20261012120000_pos_product_edit_intake.sql']) await db.exec(await migration(name))
}
