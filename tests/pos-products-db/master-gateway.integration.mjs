import assert from 'node:assert/strict'
import test, { before, beforeEach, after } from 'node:test'
import { readFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import { PGlite } from '@electric-sql/pglite'

const db = new PGlite(), migration = name => readFile(new URL(`../../supabase/migrations/${name}`, import.meta.url), 'utf8')
before(async () => {
  await db.exec(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;
    CREATE SCHEMA private; CREATE TABLE public.stores(id integer PRIMARY KEY); INSERT INTO public.stores VALUES(6),(7);
    CREATE TABLE public.products(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,store_id integer NOT NULL REFERENCES public.stores(id),
      jan_code text NOT NULL,product_name text,category text,product_group text,cost_price integer,selling_price integer,markup_rate real,
      is_active boolean DEFAULT true,tags text,brand text,updated_at timestamptz DEFAULT clock_timestamp(),UNIQUE(store_id,jan_code));
    CREATE TABLE public.pos_product_operations(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),store_id integer NOT NULL,status text NOT NULL);`)
  await db.exec(await migration('20260910090000_product_master_sync_fence.sql'))
  await db.exec(await migration('20261005123000_product_master_sync_gateway.sql'))
})
after(async () => db.close())
beforeEach(async () => db.exec("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE state='pending'"))
async function role(name, fn) { await db.exec(`SET ROLE ${name}`); try { return await fn() } finally { await db.exec('RESET ROLE') } }
const rpc = (sql, args) => role('service_role', async () => (await db.query(sql, args)).rows[0].result)
const begin = (id, store = 6, expiry = new Date(Date.now() + 100000).toISOString()) => rpc('SELECT public.begin_product_master_sync_request($1,$2,$3) AS result', [store, id, expiry])
const status = (id, store = 6) => rpc('SELECT public.get_product_master_sync_request($1,$2) AS result', [store, id])
const record = jan => ({ store_id: 6, jan_code: jan, product_name: '試験商品', category: '', product_group: null,
  cost_price: 200, selling_price: 500, markup_rate: 0.6, is_active: true, tags: 'わんわん' })

test('匿名/利用者は新版開始・状態照会を呼べずserviceでも旧開始RPCや台帳直接writeを呼べない', async () => {
  for (const who of ['anon', 'authenticated']) {
    await assert.rejects(role(who, () => db.query('SELECT public.begin_product_master_sync_request(6,$1,clock_timestamp()+interval \'1 minute\')', [randomUUID()])))
    await assert.rejects(role(who, () => db.query('SELECT public.get_product_master_sync_request(6,$1)', [randomUUID()])))
  }
  await assert.rejects(role('service_role', () => db.query('SELECT public.begin_product_master_sync(6)')))
  await assert.rejects(role('service_role', () => db.query('UPDATE public.product_master_sync_requests SET code=\'PRODUCT_SYNC_STALE\'')))
})
test('要求UUIDが実行IDになり、同店舗/他店舗のreplayは追加開始を永久拒否する', async () => {
  const id = randomUUID(), run = await begin(id)
  assert.equal(run.accepted, true); assert.equal(run.id, id); assert.equal(run.storeId, 6)
  assert.equal((await begin(id)).accepted, false); assert.equal((await begin(id)).code, 'PRODUCT_SYNC_STALE')
  const other = await begin(id, 7)
  assert.equal(other.accepted, false); assert.equal(other.code, 'PRODUCT_SYNC_INVALID_DATA')
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0].n, 1)
  const observed = await status(id)
  assert.equal(observed.state, 'pending'); assert.equal(observed.terminal, false); assert.equal(observed.runId, id)
})
test('pending-edit拒否も開始権を消費し、後から編集を解除しても同要求は開始できない', async () => {
  const id = randomUUID(); await db.exec("INSERT INTO public.pos_product_operations(store_id,status) VALUES(6,'verification_required')")
  const denied = await begin(id)
  assert.equal(denied.accepted, false); assert.equal(denied.code, 'PRODUCT_SYNC_PENDING_EDIT')
  await db.exec('DELETE FROM public.pos_product_operations')
  assert.equal((await begin(id)).accepted, false)
  const observed = await status(id)
  assert.equal(observed.terminal, true); assert.equal(observed.code, 'PRODUCT_SYNC_PENDING_EDIT'); assert.equal(observed.outcome, 'rejected')
})
test('通知保存前に終了したpending同期も新UUIDを拒否し、別店舗は独立して開始できる', async () => {
  const first = await begin(randomUUID()), denied = await begin(randomUUID())
  assert.equal(first.accepted, true); assert.equal(denied.accepted, false); assert.equal(denied.code, 'PRODUCT_SYNC_PENDING_SYNC')
  assert.equal((await begin(randomUUID(), 7)).accepted, true)
  await db.query("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1", [first.id])
  assert.equal((await begin(randomUUID())).accepted, true)
})
test('期限超過/未来過ぎる開始期限を拒否し、遅延要求を後から開始させない', async () => {
  for (const expiry of [new Date(Date.now() - 1000).toISOString(), new Date(Date.now() + 300000).toISOString()]) {
    const id = randomUUID(), result = await begin(id, 6, expiry)
    assert.equal(result.accepted, false); assert.equal(result.code, 'PRODUCT_SYNC_EXPIRED')
    assert.equal((await begin(id)).accepted, false)
  }
})
test('未作成状態の確認はtombstoneを確定し、照会後に到着した要求を拒否する', async () => {
  const id = randomUUID(), observed = await status(id)
  assert.equal(observed.found, false); assert.equal(observed.terminal, true); assert.equal(observed.code, 'PRODUCT_SYNC_EXPIRED')
  assert.equal((await begin(id)).accepted, false)
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0].n, 0)
})
test('期限切れpendingを確定拒否し、遅れてapplyしても商品は変えない', async () => {
  const id = randomUUID(); await begin(id)
  await db.query("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1", [id])
  const observed = await status(id)
  assert.equal(observed.state, 'rejected'); assert.equal(observed.terminal, true); assert.equal(observed.code, 'PRODUCT_SYNC_EXPIRED')
  await assert.rejects(rpc('SELECT public.apply_product_master_sync($1,6,$2) AS result', [id, JSON.stringify([record('late')])]), /sync expired/)
  assert.equal((await db.query("SELECT count(*)::int AS n FROM public.products WHERE jan_code='late'")).rows[0].n, 0)
})
test('ACK消失後のapplied照会はDB正本の件数だけを返し、他店舗から照会できない', async () => {
  const id = randomUUID(); await begin(id)
  await rpc('SELECT public.apply_product_master_sync($1,6,$2) AS result', [id, JSON.stringify([record('applied')])])
  const observed = await status(id)
  assert.equal(observed.terminal, true); assert.equal(observed.success, true); assert.equal(observed.state, 'applied'); assert.equal(observed.runId, id)
  assert.equal(observed.csvRowCount, 1); assert.equal(observed.syncResult.count, 1)
  assert.ok(!JSON.stringify(observed).includes('試験商品')); assert.ok(!JSON.stringify(observed).includes('source_hash'))
  await assert.rejects(status(id, 7), /PRODUCT_SYNC_INVALID_DATA/)
})

const legacyRun = async (id, store = 6) => {
  // 失効前の旧beginで作成済みの正本だけを合成する。新しい開始権を呼んでいないことも確認する。
  await db.query(`INSERT INTO public.product_master_sync_runs(id,store_id,revision)
    SELECT $1,store_id,revision FROM public.product_master_store_versions WHERE store_id=$2`, [id, store])
  return (await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0]
}
test('request記録がない旧pending実行は同UUID/storeの正本へ拘束し、未適用と誤判定しない', async () => {
  const id = randomUUID(), run = await legacyRun(id), observed = await status(id)
  assert.equal(observed.found, true); assert.equal(observed.terminal, false); assert.equal(observed.state, 'pending')
  assert.equal(observed.outcome, 'unknown'); assert.equal(observed.runId, id)
  const linked = (await db.query('SELECT state,code,run_id FROM public.product_master_sync_requests WHERE id=$1', [id])).rows[0]
  assert.deepEqual(linked, { state: 'started', code: null, run_id: id })
  assert.deepEqual((await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0], run)
  assert.equal((await begin(id)).accepted, false)
})
test('request記録がない旧applied実行は完了結果を正本から返し、新しい開始・期限延長を行わない', async () => {
  const id = randomUUID(); await legacyRun(id)
  await rpc('SELECT public.apply_product_master_sync($1,6,$2) AS result', [id, JSON.stringify([record('legacy-applied')])])
  const run = (await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0]
  const observed = await status(id)
  assert.equal(observed.state, 'applied'); assert.equal(observed.terminal, true); assert.equal(observed.success, true)
  assert.equal(observed.runId, id); assert.equal(observed.syncResult.count, 1)
  assert.deepEqual((await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0], run)
})
test('request記録がない期限切れ旧runは実行ID付きで確定拒否し、旧applyも期限拒否する', async () => {
  const id = randomUUID(); await legacyRun(id)
  await db.query("UPDATE public.product_master_sync_runs SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1", [id])
  const observed = await status(id)
  assert.equal(observed.found, true); assert.equal(observed.terminal, true); assert.equal(observed.state, 'rejected')
  assert.equal(observed.code, 'PRODUCT_SYNC_EXPIRED'); assert.equal(observed.runId, id)
  await assert.rejects(rpc('SELECT public.apply_product_master_sync($1,6,$2) AS result', [id, JSON.stringify([record('legacy-late')])]), /sync expired/)
})
test('旧runが他店舗にあるUUIDの照会は拒否し、誤った店舗のtombstoneも残さない', async () => {
  const id = randomUUID(), run = await legacyRun(id, 7)
  await assert.rejects(status(id, 6), /PRODUCT_SYNC_INVALID_DATA/)
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.product_master_sync_requests WHERE id=$1', [id])).rows[0].n, 0)
  assert.deepEqual((await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0], run)
  assert.equal((await status(id, 7)).state, 'pending')
})
test('既存tombstoneも実在同店舗の旧runだけを引き継ぎ、入力だけでは開始権を戻さない', async () => {
  const missing = randomUUID(); assert.equal((await status(missing)).found, false)
  assert.equal((await status(missing)).found, false); assert.equal((await begin(missing)).accepted, false)
  const id = randomUUID(); assert.equal((await status(id)).found, false)
  const run = await legacyRun(id), observed = await status(id)
  assert.equal(observed.state, 'pending'); assert.equal(observed.outcome, 'unknown'); assert.equal(observed.runId, id)
  assert.deepEqual((await db.query('SELECT * FROM public.product_master_sync_runs WHERE id=$1', [id])).rows[0], run)
})
