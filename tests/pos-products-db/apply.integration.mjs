async function role(name,fn) { await db.exec(`SET ROLE ${name}`);try{return await fn()}finally{await db.exec('RESET ROLE')} }
const rpc=(sql,args)=>role('service_role',async()=>(await db.query(sql,args)).rows[0].result)
const args=op=>[op.actor_id,op.store_id,op.id,op.payload_hash,op.row_version]
const event=(op,name,verified=null)=>rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result',[...args(op),name,verified])
const finish=op=>rpc('SELECT public.apply_pos_product_edit($1,$2,$3,$4,$5) AS result',args(op))
const getProduct=async id=>(await db.query('SELECT * FROM public.products WHERE id=$1',[id])).rows[0]
let sequence=10000000
async function input() {
  const jan=String(++sequence)
  const product=(await db.query(`INSERT INTO public.products(store_id,jan_code,product_name,category,product_group,supplier_name,cost_price,selling_price,brand)
    VALUES(6,$1,$2,'旧分類','旧分類','旧仕入先',50,100,'保持') RETURNING *`,[jan,'旧名'+jan])).rows[0]
  const command={kind:'update',operationId:randomUUID(),storeId:6,productId:product.id,expectedFingerprint:'a'.repeat(64),fields:{name:'新名'+jan,groupId:'g6',price:'999',cost:'499',supplierId:'s6'}}
  const catalog={groupId:'g6',groupName:'新分類',supplierId:'s6',supplierName:'新仕入先',previousPosName:'POS旧名'+jan}
  return {product,command,catalog,posId:'pos-'+jan}
}
const prepare=x=>rpc('SELECT public.prepare_pos_product_edit($1,$2,$3,$4,$5) AS result',[actor,JSON.stringify(x.command),x.posId,fp,JSON.stringify(x.catalog)])
async function verified(x) {
  let op=await prepare(x)
  op=(await rpc('SELECT public.claim_pos_product_operation($1,$2,$3,$4,$5) AS result',args(op))).operation
  op=await event(op,'dispatch_returned')
  return event(op,'pos_verified',fp)
}
test('POS確認前・匿名・他店舗・別利用者は商品反映を行えない',async()=>{
  const x=await input();const op=await prepare(x);const before=await getProduct(x.product.id)
  await assert.rejects(finish(op))
  await assert.rejects(finish({...op,actor_id:other}))
  await assert.rejects(finish({...op,store_id:7}))
  for(const who of ['anon','authenticated']) await assert.rejects(role(who,()=>db.query('SELECT public.apply_pos_product_edit($1,$2,$3,$4,$5)',args(op))))
  assert.deepEqual(await getProduct(x.product.id),before)
  await event(op,'reject_before_dispatch')
})
test('商品・POSリンク・旧名称別名・監査・完了・予約解放を同時に反映し、再実行は無変更',async()=>{
  const x=await input()
  await db.query("INSERT INTO public.products(store_id,jan_code,product_name) VALUES(7,$1,'他店舗')",[x.product.jan_code])
  const otherBefore=(await db.query('SELECT * FROM public.products WHERE store_id=7')).rows
  await db.query('INSERT INTO public.inventory_product_settings(store_id,product_id,manually_inactive,updated_by) VALUES(6,$1,true,$2)',[x.product.id,actor])
  // 実際の手動停止操作は設定と商品状態を同時に変更する。
  await db.query('UPDATE public.products SET is_active=false WHERE id=$1',[x.product.id])
  const settings=(await db.query('SELECT * FROM public.inventory_product_settings')).rows
  const session=(await db.query('INSERT INTO public.inventory_sessions(store_id,started_by,updated_by) VALUES(6,$1,$1) RETURNING id',[actor])).rows[0].id
  await db.query(`INSERT INTO public.inventory_session_items(session_id,store_id,product_id,jan_snapshot,product_name_snapshot,
    counted_quantity,counted_at,counted_by,created_by,updated_by) VALUES($1,6,$2,$3,$4,12,'2026-09-10T01:00:00Z',$5,$5,$5)`,[session,x.product.id,x.product.jan_code,x.product.product_name,actor])
  const counted=(await db.query('SELECT * FROM public.inventory_session_items')).rows
  const op=await verified(x);const done=await finish(op)
  assert.equal(done.status,'completed');assert.equal(done.send_attempts,1)
  const p=await getProduct(x.product.id)
  assert.equal(p.product_name,x.command.fields.name);assert.equal(p.selling_price,999);assert.equal(p.cost_price,499)
  assert.equal(p.product_group,'新分類');assert.equal(p.supplier_name,'新仕入先');assert.equal(p.brand,'保持');assert.equal(p.is_active,false)
  const aliases=(await db.query('SELECT alias_name FROM public.product_aliases WHERE product_id=$1 ORDER BY alias_name',[p.id])).rows.map(r=>r.alias_name)
  assert.deepEqual(new Set(aliases),new Set([x.product.product_name,x.catalog.previousPosName]))
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.pos_product_operation_locks WHERE operation_id=$1',[op.id])).rows[0].n,0)
  assert.equal((await db.query('SELECT pos_product_id FROM public.pos_product_links WHERE product_id=$1',[p.id])).rows[0].pos_product_id,x.posId)
  assert.deepEqual(await finish(op),done)
  assert.deepEqual(await getProduct(p.id),p)
  assert.deepEqual((await db.query('SELECT * FROM public.products WHERE store_id=7')).rows,otherBefore)
  assert.deepEqual((await db.query('SELECT * FROM public.inventory_product_settings')).rows,settings)
  assert.deepEqual((await db.query('SELECT * FROM public.inventory_session_items')).rows,counted)
  assert.equal((await db.query("SELECT count(*)::int AS n FROM public.pos_product_operation_events WHERE operation_id=$1 AND new_status='completed'",[op.id])).rows[0].n,1)
})
test('受付後のローカル値変更は上書きせず、ブランドだけの変更は保持して反映する',async()=>{
  const x=await input();let op=await verified(x)
  await db.query('UPDATE public.products SET selling_price=777 WHERE id=$1',[x.product.id])
  await assert.rejects(finish(op),/changed/)
  op=await event(op,'db_failed')
  assert.equal(op.status,'db_pending');assert.equal((await getProduct(x.product.id)).selling_price,777)
  const y=await input();const ok=await verified(y)
  await db.query("UPDATE public.products SET brand='別端末ブランド' WHERE id=$1",[y.product.id])
  await finish(ok)
  assert.equal((await getProduct(y.product.id)).brand,'別端末ブランド')
})
test('受付再送でDB基準値を取り直さず、カタログIDと名称の改変を拒否する',async()=>{
  const x=await input();const op=await prepare(x)
  assert.deepEqual(await prepare(x),op)
  await assert.rejects(prepare({...x,catalog:{...x.catalog,groupName:'改変'}}))
  await assert.rejects(prepare({...x,command:{...x.command,operationId:randomUUID()},catalog:{...x.catalog,groupId:'other'}}))
  await event(op,'reject_before_dispatch')
})
test('反映中の制約違反は全件を戻し、DBだけの復旧で一度だけ完了する',async()=>{
  const x=await input();let op=await verified(x);const before=await getProduct(x.product.id)
  await db.exec("ALTER TABLE public.pos_product_links ADD CONSTRAINT fixture_fail CHECK(pos_product_id <> '"+x.posId+"')")
  await assert.rejects(finish(op))
  assert.deepEqual(await getProduct(x.product.id),before)
  assert.equal((await db.query('SELECT count(*)::int AS n FROM public.pos_product_edit_receipts WHERE operation_id=$1',[op.id])).rows[0].n,0)
  op=await event(op,'db_failed')
  await db.exec('ALTER TABLE public.pos_product_links DROP CONSTRAINT fixture_fail')
  assert.equal((await finish(op)).status,'completed')
  assert.equal((await finish(op)).send_attempts,1)
})
