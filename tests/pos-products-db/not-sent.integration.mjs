test('新RPCと証拠はservice専用/immutableで、汎用イベントや直接UPDATEでは終端化できない', async () => {
  const x = await fixture(), before = await state(x)
  for (const who of ['anon', 'authenticated']) await assert.rejects(role(who, () => db.query(resolveSql, resolveArgs(x))))
  await assert.rejects(db.query("UPDATE public.pos_product_operations SET status='not_sent',row_version=row_version+1,last_event='dispatch_not_sent' WHERE id=$1", [x.op.id]))
  await assert.rejects(rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result', [...opArgs(x.op), 'dispatch_not_sent', null]))
  assert.deepEqual(await state(x), before)
  await resolve(x)
  for (const who of ['anon', 'authenticated', 'service_role']) await assert.rejects(role(who, () => db.query('SELECT * FROM public.pos_product_edit_not_sent_proofs')))
  for (const sql of ['UPDATE public.pos_product_edit_not_sent_proofs SET stop_code=stop_code', 'DELETE FROM public.pos_product_edit_not_sent_proofs', 'TRUNCATE public.pos_product_edit_not_sent_proofs']) await assert.rejects(db.exec(sql), /append only/)
  const rights = (await db.query("SELECT prosecdef,proconfig,has_function_privilege('service_role',$1,'EXECUTE') AS service,has_function_privilege('anon',$1,'EXECUTE') AS anon FROM pg_proc WHERE oid=$1::regprocedure", [signature])).rows[0]
  assert.equal(rights.prosecdef, true); assert.equal(rights.service, true); assert.equal(rights.anon, false)
  assert.ok(rights.proconfig.some(value => value.startsWith('search_path=')))
})

