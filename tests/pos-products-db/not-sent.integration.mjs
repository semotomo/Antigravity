let sequence = 40000000
async function fixture(store = 6, claim = true, status = 'uncertain', executionWindow = 110000) {
  const jan = String(++sequence)
  const product = (await db.query(`INSERT INTO public.products(store_id,jan_code,product_name,category,product_group,supplier_name,cost_price,selling_price,brand)
    VALUES($1,$2,'旧名','分類','分類',null,50,100,'保持') RETURNING *`, [store, jan])).rows[0]
  const reviewedAt = Number((await db.query('SELECT floor(extract(epoch FROM clock_timestamp())*1000)::bigint AS n')).rows[0].n)
  const before = { identity: { posProductId: 'pos-' + jan, officeId: store === 6 ? '11054' : '11053', groupId: store === 6 ? '11099' : '11098',
    salesKind: 'retail', productCode: '', manufacturerCode: jan, exclusiveStore: true },
  fields: { name: '旧名', groupId: 'g1', price: '100', cost: '50', supplierId: null },
  settings: { nameKana: '', abbreviation: '', taxId: '0', priceScope: 'all', priceMode: 'fixed', supplierScope: 'all', otherSettingsFingerprint: 'c'.repeat(64) },
  groups: [{ id: 'g1', name: '分類' }], suppliers: [] }
  const nextFields = { ...before.fields, name: '新名' }
  const fingerprint = fields => JSON.stringify({ version: 'pos-product-edit.v1', storeId: store, productId: product.id, janCode: jan,
    identity: before.identity, fields, settings: before.settings })
  const beforeText = fingerprint(before.fields), expectedText = fingerprint(nextFields)
  const command = { storeId: store, operationId: randomUUID(), productId: product.id, expectedFingerprint: hash(beforeText), kind: 'update', fields: nextFields }
  const commandText = JSON.stringify(command)
  let op = await rpc('SELECT public.prepare_pos_product_edit($1,$2,$3,$4,$5) AS result',
    [manager, commandText, before.identity.posProductId, hash(expectedText), JSON.stringify({ groupId: 'g1', groupName: '分類', supplierId: null, supplierName: null, previousPosName: '旧名' })])
  // 配列を含むdispatchだけは既存canonical形式を使う。
  const sorted = value => value && typeof value === 'object' ? Array.isArray(value) ? '[' + value.map(sorted).join(',') + ']'
    : '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + sorted(value[key])).join(',') + '}' : JSON.stringify(value)
  const dispatchText = sorted({ operationId: op.id, actorId: manager, storeId: store, janCode: jan, before, patch: { goodsName: '新名' }, expiresAt: reviewedAt + executionWindow })
  const dispatchHash = hash(dispatchText)
  await rpc('SELECT public.register_pos_product_edit_dispatch($1,$2,$3,$4,$5,$6,$7,$8,$9) AS result', [...opArgs(op), dispatchText, beforeText, expectedText, reviewedAt])
  if (claim) {
    op = (await rpc('SELECT public.claim_pos_product_operation($1,$2,$3,$4,$5) AS result', opArgs(op))).operation
    if (status === 'uncertain') op = await rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result', [...opArgs(op), 'outcome_unknown', null])
  }
  const proof = { version: 1, audience: 'kennel.pos-product-not-sent.v1', operationId: op.id, actorId: manager, storeId: store,
    dispatchHash, requestSignature: 'a'.repeat(64), stopCode: codes[3], occurredAt: reviewedAt }
  // HMAC検証はNextの責務。DBテストでは安全な合成証拠だけを渡す。
  proof.signature = createHmac('sha256', 'test-only-not-a-key').update(canonical(proof)).digest('hex')
  return { product, command, commandText, op, dispatchText, dispatchHash, expectedText, reviewedAt, proof }
}
const resolveArgs = (x, proofText = canonical(x.proof), op = x.op) => [...opArgs(op), x.dispatchHash, proofText]
const resolve = (x, proofText, op) => rpc(resolveSql, resolveArgs(x, proofText, op))

test('両店舗・既知5停止codeを終端not_sent/send1へ一度だけ記録し、3予約を解放する', async () => {
  for (const store of [6, 7]) for (const code of codes) {
    const x = await fixture(store), previous = await state(x)
    x.proof.stopCode = code
    const { signature: priorSignature, ...unsigned } = x.proof
    assert.match(priorSignature, /^[0-9a-f]{64}$/)
    x.proof.signature = createHmac('sha256', 'test-only-not-a-key').update(canonical(unsigned)).digest('hex')
    const products = (await db.query('SELECT * FROM public.products ORDER BY id')).rows
    const intent = (await db.query('SELECT * FROM public.pos_product_edit_intents WHERE operation_id=$1', [x.op.id])).rows
    const first = await resolve(x)
    assert.deepEqual(Object.keys(first).sort(), ['operation', 'recovered'])
    assert.equal(first.recovered, true); assert.equal(first.operation.status, 'not_sent'); assert.equal(first.operation.send_attempts, 1)
    assert.equal(first.operation.verified_fingerprint, null); assert.equal(first.operation.row_version, x.op.row_version + 1)
    assert.equal(first.operation.last_event, 'dispatch_not_sent'); assert.equal(await count('pos_product_operation_locks', x.op.id), 0)
    assert.equal(await count('pos_product_operation_events', x.op.id), previous.events + 1)
    const proof = (await db.query('SELECT * FROM public.pos_product_edit_not_sent_proofs WHERE operation_id=$1', [x.op.id])).rows[0]
    assert.equal(proof.proof_text, canonical(x.proof)); assert.equal(proof.proof_hash, hash(proof.proof_text))
    assert.equal(proof.actor_id, manager); assert.equal(proof.dispatch_hash, x.dispatchHash); assert.equal(proof.stop_code, code)
    assert.equal(Number(proof.source_row_version), x.op.row_version)
    assert.deepEqual(await resolve(x), { ...first, recovered: false })
    assert.deepEqual(await resolve(x, undefined, first.operation), { ...first, recovered: false })
    assert.equal(await count('pos_product_operation_events', x.op.id), previous.events + 1)
    assert.equal(await count('pos_product_edit_not_sent_proofs', x.op.id), 1)
    assert.deepEqual((await db.query('SELECT * FROM public.products ORDER BY id')).rows, products)
    assert.deepEqual((await db.query('SELECT * FROM public.pos_product_edit_intents WHERE operation_id=$1', [x.op.id])).rows, intent)
    await assert.rejects(rpc('SELECT public.consume_pos_product_edit_dispatch($1,$2,$3,$4) AS result', [manager, store, x.op.id, x.dispatchHash]))
    assert.equal((await rpc('SELECT public.claim_pos_product_operation($1,$2,$3,$4,$5) AS result', opArgs(first.operation))).claimed, false)
  }
})

