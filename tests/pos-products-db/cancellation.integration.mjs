test('dispatching/uncertain/pos_confirmed/db_pendingの取消は拒否し、監査/予約を保持する', async () => {
  for (const status of ['dispatching', 'uncertain', 'pos_confirmed', 'db_pending']) {
    const x = await fixture()
    x.op = (await rpc('SELECT public.claim_pos_product_operation($1,$2,$3,$4,$5) AS result', [manager, 6, x.op.id, x.op.payload_hash, x.op.row_version])).operation
    if (status !== 'dispatching') x.op = await rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result', [manager, 6, x.op.id, x.op.payload_hash, x.op.row_version, 'outcome_unknown', null])
    if (['pos_confirmed', 'db_pending'].includes(status)) x.op = await rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result', [manager, 6, x.op.id, x.op.payload_hash, x.op.row_version, 'pos_verified', 'b'.repeat(64)])
    if (status === 'db_pending') x.op = await rpc('SELECT public.record_pos_product_operation_result($1,$2,$3,$4,$5,$6,$7) AS result', [manager, 6, x.op.id, x.op.payload_hash, x.op.row_version, 'db_failed', null])
    const before = await inspect(x), events = await count('pos_product_operation_events', x.op.id)
    await assert.rejects(cancel(x)); assert.deepEqual(await inspect(x), before)
    assert.equal(await count('pos_product_operation_events', x.op.id), events)
    assert.equal(await count('pos_product_operation_locks', x.op.id), 3)
    assert.equal(await count('pos_product_operation_cancellations', x.op.id), 0)
  }
})
test('service専用RPC/RLS/immutable取消監査を維持し、ブラウザや直接更新で迂回不可', async () => {
  const x = await fixture(6, false); await cancel(x)
  for (const role of ['anon', 'authenticated']) {
    await db.exec('SET ROLE ' + role)
    try {
      await assert.rejects(db.query(cancelSql, args(x))); await assert.rejects(db.query(getSql, args(x)))
      await assert.rejects(db.query('SELECT * FROM pos_product_operation_cancellations'))
    } finally { await db.exec('RESET ROLE') }
  }
  for (const sql of ['DELETE FROM pos_product_operation_cancellations', 'UPDATE pos_product_operation_cancellations SET reason=reason', 'TRUNCATE pos_product_operation_cancellations']) await assert.rejects(db.exec(sql))
})

