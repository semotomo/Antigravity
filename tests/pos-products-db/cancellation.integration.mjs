const count = async (table, id) => (await db.query(`SELECT count(*)::int n FROM public.${table} WHERE operation_id=$1`, [id])).rows[0].n

test('prepared/send0の明示取消は監査と3予約解放を同transactionで行い、再実行も冪等', async () => {
  for (const store of [6, 7]) {
    const x = await fixture(store), products = (await db.query('SELECT * FROM products ORDER BY id')).rows
    const first = await cancel(x)
    assert.equal(first.operation.status, 'rejected'); assert.equal(first.operation.send_attempts, 0)
    assert.equal(first.operation.row_version, 1); assert.equal(first.operation.last_event, 'reject_before_dispatch')
    assert.equal(first.cancellation.reason, 'cancel_prepared')
    assert.equal(await count('pos_product_operation_locks', x.op.id), 0)
    assert.equal(await count('pos_product_operation_events', x.op.id), 2)
    assert.equal(await count('pos_product_operation_cancellations', x.op.id), 1)
    assert.deepEqual(await cancel(x), first); assert.deepEqual(await inspect(x), first)
    assert.deepEqual((await db.query('SELECT * FROM products ORDER BY id')).rows, products)
    assert.equal(await count('pos_product_edit_receipts', x.op.id), 0)
  }
})
