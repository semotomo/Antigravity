async function asRole(name, user, fn) {
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [user || ''])
  await db.exec(`SET ROLE ${name}`)
  try { return await fn() } finally { await db.exec('RESET ROLE') }
}
