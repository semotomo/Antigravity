test('匿名・利用者・serviceの旧直接書込み、列GRANT、削除、TRUNCATEを全て拒否する', async () => {
  for (const who of ['anon','authenticated','service_role']) {
    for (const sql of ["UPDATE public.products SET product_name='改ざん' WHERE id=1",
      "INSERT INTO public.products(store_id,jan_code) VALUES(6,'new')",'DELETE FROM public.products WHERE id=1','TRUNCATE public.products CASCADE']) {
      const before = await snapshot()
      await assert.rejects(asRole(who, manager, () => db.exec(sql)))
      assert.deepEqual(await snapshot(), before)
    }
  }
  await assert.rejects(asRole('anon', null, () => db.query('SELECT product_name FROM public.products')))
})
test('閲覧は本人の店舗だけで、全店service読取りは許可する', async () => {
  assert.deepEqual((await asRole('authenticated', manager, () => db.query('SELECT DISTINCT store_id FROM public.products'))).rows,[{store_id:6}])
  assert.deepEqual((await asRole('authenticated', viewer, () => db.query('SELECT DISTINCT store_id FROM public.products'))).rows,[{store_id:7}])
  assert.equal((await asRole('authenticated', outsider, () => db.query('SELECT * FROM public.products'))).rows.length,0)
  assert.equal((await asRole('service_role', null, () => db.query('SELECT * FROM public.products'))).rows.length,3)
})
test('一部CSVが来ても欠落商品を停止せず、店舗別同期RPCだけが商品を更新できる', async () => {
  const before = await snapshot()
  await assert.rejects(asRole('service_role', null, () => db.query('SELECT public.begin_product_master_sync(6)')))
  const run = (await asRole('service_role', null, () => db.query("SELECT public.begin_product_master_sync_request(6,$1,clock_timestamp()+interval '1 minute') AS value",[randomUUID()]))).rows[0].value
  assert.equal(run.accepted,true)
  const result = (await asRole('service_role', null, () => db.query('SELECT public.apply_product_master_sync($1,6,$2::jsonb) AS value',
    [run.id,JSON.stringify([row('001')])]))).rows[0].value
  assert.equal(result.count,1); assert.equal(result.deactivatedCount,0)
  const current = await snapshot()
  assert.equal(current[0].product_name,'更新名');assert.equal(current[0].brand,'維持');assert.equal(current[0].supplier_name,'仕入先')
  assert.deepEqual(current.slice(1),before.slice(1))
})
test('棚卸しで理由付きの商品停止・再開、他店舗拒否は維持し、数量は変更しない', async () => {
  const stop = () => db.query("SELECT public.set_inventory_product_status(6,'001',false,'棚卸しで確認') AS value")
  await assert.rejects(asRole('authenticated', viewer, stop))
  await asRole('authenticated', manager, stop)
  assert.equal((await snapshot())[0].is_active,false)
  assert.equal((await db.query('SELECT count(*)::integer AS n FROM public.inventory_product_status_changes')).rows[0].n,1)
  await asRole('authenticated', manager, () => db.query("SELECT public.set_inventory_product_status(6,'001',true,'再開確認')"))
  assert.equal((await snapshot())[0].is_active,true)
  assert.equal((await db.query('SELECT count(*)::integer AS n FROM public.inventory_session_items')).rows[0].n,0)
})
